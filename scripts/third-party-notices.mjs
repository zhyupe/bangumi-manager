import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import {
  existsSync,
  readdirSync,
  readFileSync,
  realpathSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const packages = new Map();
const texts = new Map();
const missing = [];
const supplements = JSON.parse(
  readFileSync(path.join(root, "third-party/notice-sources.json"), "utf8"),
);

function licenseFiles(directory, nested = false) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const filename = path.join(directory, entry.name);
    if (
      entry.isFile() &&
      /^(?:(?:third.party.)?licen[cs]e|copying|copyright|notice|unlicense)([._-]|$)/i.test(
        entry.name,
      )
    )
      return [filename];
    if (!nested && entry.isDirectory() && /^licen[cs]es?$/i.test(entry.name)) {
      return readdirSync(filename, { withFileTypes: true })
        .filter((file) => file.isFile())
        .map((file) => path.join(filename, file.name));
    }
    return [];
  });
}

function record(id, directory, license, url, author) {
  if (packages.has(id)) return;
  const files = [
    ...licenseFiles(directory),
    ...(supplements[id]?.directory
      ? licenseFiles(path.join(root, supplements[id].directory))
      : []),
  ];
  packages.set(
    id,
    `${id} | ${license || "See package source"}${url ? ` | ${url}` : ""}${author ? ` | Manifest attribution: ${author}` : ""}`,
  );
  if (!files.length) missing.push(id);
  for (const filename of files.sort()) {
    const text = readFileSync(filename, "utf8")
      .replace(/^\uFEFF/, "")
      .replace(/\r\n/g, "\n")
      .replace(/[ \t]+$/gm, "")
      .trim();
    const hash = createHash("sha256").update(text).digest("hex");
    const notice = texts.get(hash) || { text, packages: new Set() };
    notice.packages.add(id);
    texts.set(hash, notice);
  }
}

const visited = new Set();
function visitNpm(name, from, optional = false) {
  let directory;
  for (let current = from; ; current = path.dirname(current)) {
    const candidate = path.join(current, "node_modules", name);
    if (existsSync(path.join(candidate, "package.json"))) {
      directory = realpathSync(candidate);
      break;
    }
    if (current === path.dirname(current)) break;
  }
  if (!directory) {
    if (optional) return;
    throw new Error(`Missing ${name}; run pnpm install --frozen-lockfile.`);
  }
  if (visited.has(directory)) return;
  visited.add(directory);
  const pkg = JSON.parse(
    readFileSync(path.join(directory, "package.json"), "utf8"),
  );
  const license =
    typeof pkg.license === "string" ? pkg.license : pkg.license?.type;
  const url =
    typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
  const author = typeof pkg.author === "string" ? pkg.author : pkg.author?.name;
  record(`npm:${pkg.name}@${pkg.version}`, directory, license, url, author);
  for (const dep of Object.keys(pkg.dependencies || {}))
    visitNpm(dep, directory, dep in (pkg.optionalDependencies || {}));
  for (const dep of Object.keys({
    ...pkg.optionalDependencies,
    ...pkg.peerDependencies,
  }))
    visitNpm(dep, directory, true);
}
const app = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
for (const name of Object.keys({ ...app.dependencies, ...app.devDependencies }))
  visitNpm(name, root);

const metadata = JSON.parse(
  execFileSync(
    "cargo",
    [
      "metadata",
      "--manifest-path",
      "src-tauri/Cargo.toml",
      "--format-version",
      "1",
      "--locked",
      "--filter-platform",
      "x86_64-pc-windows-msvc",
    ],
    { cwd: root, encoding: "utf8", maxBuffer: 32 * 1024 * 1024 },
  ),
);
const resolved = new Set(metadata.resolve.nodes.map((node) => node.id));
for (const pkg of metadata.packages) {
  if (!pkg.source || !resolved.has(pkg.id)) continue;
  record(
    `crate:${pkg.name}@${pkg.version}`,
    path.dirname(pkg.manifest_path),
    pkg.license,
    pkg.repository,
  );
}
record(
  "shadcn/ui (vendored components)",
  path.join(root, "src/components/ui"),
  "MIT",
  "https://github.com/shadcn-ui/ui",
);

const lines = [
  "Bangumi Manager — third-party notices",
  "",
  "Generated by scripts/third-party-notices.mjs from installed frontend packages and the locked Windows Rust dependency graph. Includes build and test dependencies. Each component retains its own license. Identical license texts are grouped without removing attribution. Supplement sources are recorded in third-party/notice-sources.json. For archives that declare MIT but omit a license file, the standard MIT text is supplied with attribution from the package manifest.",
  "",
  "PACKAGE INVENTORY",
  "",
  ...[...packages.values()].sort(),
  "",
  "LICENSE AND NOTICE TEXTS",
  "",
];
for (const notice of [...texts.values()].sort((a, b) =>
  [...a.packages].sort()[0].localeCompare([...b.packages].sort()[0], "en"),
)) {
  lines.push(
    "=".repeat(78),
    ...[...notice.packages].sort(),
    "-".repeat(78),
    notice.text,
    "",
  );
}
if (missing.length) {
  lines.push(
    "=".repeat(78),
    "Packages without standalone license files in the installed archive",
    "Their declared license and source are listed in the inventory above.",
    ...missing.sort(),
    "",
  );
}
writeFileSync(path.join(root, "THIRD_PARTY_NOTICES.txt"), lines.join("\n"));
console.log(
  `Wrote notices for ${packages.size} components (${texts.size} distinct texts).`,
);
if (missing.length)
  console.log(`No standalone notice file: ${missing.sort().join(", ")}`);
